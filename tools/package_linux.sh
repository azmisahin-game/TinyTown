#!/usr/bin/env bash
#
# Build a Linux release tarball for TinyTown.
#
# Usage: tools/package_linux.sh <build-dir> <output-dir> [version]
#
# Produces TinyTown-<version>-linux-x64.tar.gz containing the application
# binary, the quick-start text in both languages, the licence, and the
# third-party notices. It does not bundle SDL2 or OpenGL: those are system
# dependencies on Linux and are documented rather than shipped.
#
# The script fails loudly if any expected file is missing or if the packaged
# binary has unresolved shared-library dependencies.

set -euo pipefail

BUILD_DIR="${1:-build}"
OUT_DIR="${2:-dist}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

cd "$REPO_ROOT"

# Version comes from CMakeLists.txt so the package name and the project version
# can never drift apart.
if [[ $# -ge 3 ]]; then
    VERSION="$3"
else
    VERSION="$(sed -n 's/^[[:space:]]*VERSION[[:space:]]\+\([0-9][0-9.]*\).*/\1/p' CMakeLists.txt | head -1)"
fi
if [[ -z "$VERSION" ]]; then
    echo "error: could not read the project version from CMakeLists.txt" >&2
    exit 1
fi

APP_BIN="$BUILD_DIR/tinytown"
if [[ ! -x "$APP_BIN" ]]; then
    echo "error: application binary not found or not executable: $APP_BIN" >&2
    exit 1
fi

PKG_NAME="TinyTown-v${VERSION}-linux-x64"
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

STAGE_ROOT="$STAGE/$PKG_NAME"
mkdir -p "$STAGE_ROOT"

echo "Packaging $PKG_NAME from $BUILD_DIR"

# --- Application binary ------------------------------------------------------
install -m 0755 "$APP_BIN" "$STAGE_ROOT/tinytown"

# --- Quick-start text, generated by the application itself -------------------
# Running --help means the packaged instructions always match the real binary.
# The staged path is rewritten to the plain name so the file does not leak a
# build-machine temp directory. If the binary cannot run here, fall back to the
# README instead of writing an empty file.
write_quickstart() {
    local lang="$1"
    local out="$2"
    if "$STAGE_ROOT/tinytown" --help --lang "$lang" > "$out" 2>/dev/null; then
        sed -i "s|$STAGE_ROOT/tinytown|tinytown|g" "$out"
        echo "wrote $(basename "$out") from the binary"
    else
        echo "warning: could not run the binary for --help ($lang); using the README instead" >&2
        cp README.md "$out"
    fi
}

write_quickstart tr "$STAGE_ROOT/QUICKSTART_TR.txt"
write_quickstart en "$STAGE_ROOT/QUICKSTART_EN.txt"

# --- Licence and notices -----------------------------------------------------
install -m 0644 LICENSE "$STAGE_ROOT/LICENSE"
install -m 0644 THIRD-PARTY-NOTICES.md "$STAGE_ROOT/THIRD-PARTY-NOTICES.md"

# --- Version and dependency notes --------------------------------------------
{
    echo "TinyTown v${VERSION} (linux-x64)"
    echo
    echo "Run: ./tinytown"
    echo "Language: Turkish by default. Press L in the application to switch to"
    echo "English, or start with --lang en."
    echo
    echo "System dependencies (NOT bundled, install them with your package manager):"
    echo "  - SDL2 runtime, version 2.0.16 or newer"
    echo "  - OpenGL runtime (Mesa or a vendor driver)"
    echo
    echo "Debian/Ubuntu:"
    echo "  sudo apt-get install -y libsdl2-2.0-0 libgl1"
    echo "Fedora:"
    echo "  sudo dnf install -y SDL2 mesa-libGL"
    echo "Arch:"
    echo "  sudo pacman -S sdl2 mesa"
    echo
    echo "Verified with SDL2 2.32.4. Older 2.x releases may work but were not tested."
} > "$STAGE_ROOT/RUNTIME-REQUIREMENTS.txt"

# --- Verify the packaged binary's shared libraries ---------------------------
# ldd reports a missing dependency with "not found". A package that cannot start
# must not be published.
if command -v ldd >/dev/null 2>&1; then
    echo "Shared-library check (ldd):"
    ldd "$STAGE_ROOT/tinytown" | sed 's/^/  /'
    if ldd "$STAGE_ROOT/tinytown" | grep -q "not found"; then
        echo "error: the packaged binary has unresolved shared-library dependencies:" >&2
        ldd "$STAGE_ROOT/tinytown" | grep "not found" >&2
        exit 1
    fi
    echo "no unresolved dependencies"
else
    echo "warning: ldd not available; skipping the shared-library check" >&2
fi

# --- Verify the packaged binary actually runs --------------------------------
# --help exercises process start-up, argument parsing and exit codes.
if ! "$STAGE_ROOT/tinytown" --help >/dev/null 2>&1; then
    echo "error: the packaged binary failed to run --help" >&2
    exit 1
fi
echo "packaged binary runs --help successfully"

# --- Archive -----------------------------------------------------------------
mkdir -p "$OUT_DIR"
OUT_PATH="$OUT_DIR/${PKG_NAME}.tar.gz"
rm -f "$OUT_PATH"
tar -czf "$OUT_PATH" -C "$STAGE" "$PKG_NAME"

echo
echo "Package written: $OUT_PATH"
echo "Contents:"
tar -tzf "$OUT_PATH" | sed 's/^/  /'

# Refuse to publish an archive that is missing something it promised.
ARCHIVE_LIST="$STAGE/archive-list.txt"
tar -tzf "$OUT_PATH" > "$ARCHIVE_LIST"
for required in \
    "$PKG_NAME/tinytown" \
    "$PKG_NAME/QUICKSTART_TR.txt" \
    "$PKG_NAME/QUICKSTART_EN.txt" \
    "$PKG_NAME/LICENSE" \
    "$PKG_NAME/THIRD-PARTY-NOTICES.md" \
    "$PKG_NAME/RUNTIME-REQUIREMENTS.txt"
do
    if ! grep -qxF "$required" "$ARCHIVE_LIST"; then
        echo "error: package is missing $required" >&2
        exit 1
    fi
done
echo "all expected files present in the archive"
