# Build a Windows release ZIP for TinyTown.
#
# Usage: tools/package_windows.ps1 -BuildDir <dir> -OutputDir <dir> -Sdl2Root <dir> [-Version <v>]
#
# Produces TinyTown-v<version>-windows-x64.zip containing tinytown.exe, the
# SDL2 runtime DLL it needs, the quick-start text in both languages, the
# licence, and the third-party notices. Only SDL2.dll is copied from the SDK,
# never the whole SDK tree.
#
# The script fails loudly if any expected file is missing, or if the packaged
# executable cannot start from the staged directory.

param(
    [Parameter(Mandatory = $true)][string]$BuildDir,
    [Parameter(Mandatory = $true)][string]$OutputDir,
    [Parameter(Mandatory = $true)][string]$Sdl2Root,
    [string]$Version = ""
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
Set-Location $repoRoot

if ([string]::IsNullOrWhiteSpace($Version)) {
    $line = Select-String -Path 'CMakeLists.txt' -Pattern '^\s*VERSION\s+([0-9][0-9.]*)' |
        Select-Object -First 1
    if (-not $line) {
        throw 'Could not read the project version from CMakeLists.txt'
    }
    $Version = $line.Matches[0].Groups[1].Value
}
if ([string]::IsNullOrWhiteSpace($Version)) {
    throw 'Project version is empty'
}

$exe = Join-Path $BuildDir 'tinytown.exe'
if (-not (Test-Path -LiteralPath $exe -PathType Leaf)) {
    throw "Application executable not found: $exe"
}

$sdlDll = Join-Path $Sdl2Root 'lib\x64\SDL2.dll'
if (-not (Test-Path -LiteralPath $sdlDll -PathType Leaf)) {
    throw "SDL2 runtime DLL not found: $sdlDll"
}

$packageName = "TinyTown-v$Version-windows-x64"
$stage = Join-Path ([System.IO.Path]::GetTempPath()) ("tinytown-pkg-" + [guid]::NewGuid().ToString('N'))
$stageRoot = Join-Path $stage $packageName
New-Item -ItemType Directory -Path $stageRoot -Force | Out-Null

try {
    Write-Host "Packaging $packageName from $BuildDir"

    # --- Application binary and its one runtime dependency --------------------
    Copy-Item -LiteralPath $exe -Destination $stageRoot -Force
    Copy-Item -LiteralPath $sdlDll -Destination $stageRoot -Force

    # --- Quick-start text, generated by the application itself ---------------
    # Running --help means the packaged instructions always match the real
    # binary. If the binary cannot run here, fall back to the README instead of
    # writing an empty file.
    function Write-QuickStart {
        param([string]$Language, [string]$FileName)
        $target = Join-Path $stageRoot $FileName
        & (Join-Path $stageRoot 'tinytown.exe') --help --lang $Language > $target 2>$null
        if ($LASTEXITCODE -eq 0 -and (Get-Item -LiteralPath $target).Length -gt 0) {
            Write-Host "wrote $FileName from the binary"
        } else {
            Write-Warning "could not run the binary for --help ($Language); using the README instead"
            Copy-Item -LiteralPath 'README.md' -Destination $target -Force
        }
    }
    Write-QuickStart -Language 'tr' -FileName 'QUICKSTART_TR.txt'
    Write-QuickStart -Language 'en' -FileName 'QUICKSTART_EN.txt'

    # --- Licence and notices -------------------------------------------------
    Copy-Item -LiteralPath 'LICENSE' -Destination $stageRoot -Force
    Copy-Item -LiteralPath 'THIRD-PARTY-NOTICES.md' -Destination $stageRoot -Force

    # --- Version and dependency notes ----------------------------------------
    $notes = @"
TinyTown v$Version (windows-x64)

Run: tinytown.exe
Language: Turkish by default. Press L in the application to switch to English,
or start with: tinytown.exe --lang en

This package includes SDL2.dll because Windows has no system package manager
for SDL2. OpenGL comes from your graphics driver; there is nothing else to
install.

Verified on Windows Server 2022 with the MSVC 2022 toolchain. The interactive
window was not launched on the build machine, which has no display.
"@
    Set-Content -LiteralPath (Join-Path $stageRoot 'RUNTIME-REQUIREMENTS.txt') `
        -Value $notes -Encoding utf8

    # --- Verify the packaged executable actually starts ----------------------
    # Run from the staged directory so DLL resolution matches the real package.
    Push-Location $stageRoot
    try {
        & '.\tinytown.exe' --help > $null 2>&1
        if ($LASTEXITCODE -ne 0) {
            throw "The packaged executable failed to run --help (exit code $LASTEXITCODE)"
        }
        Write-Host 'packaged executable runs --help successfully'
    } finally {
        Pop-Location
    }

    # --- Archive -------------------------------------------------------------
    if (-not (Test-Path -LiteralPath $OutputDir)) {
        New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null
    }
    $outputPath = Join-Path $OutputDir "$packageName.zip"
    if (Test-Path -LiteralPath $outputPath) { Remove-Item -LiteralPath $outputPath -Force }
    Compress-Archive -Path $stageRoot -DestinationPath $outputPath -CompressionLevel Optimal

    Write-Host ''
    Write-Host "Package written: $outputPath"

    # Refuse to publish an archive that is missing something it promised.
    # The archive is expanded into a scratch directory and checked on disk, so
    # the check does not depend on any zip assembly being loaded.
    $verifyDir = Join-Path $stage 'verify'
    New-Item -ItemType Directory -Path $verifyDir -Force | Out-Null
    Expand-Archive -LiteralPath $outputPath -DestinationPath $verifyDir -Force

    $extractedRoot = Join-Path $verifyDir $packageName
    Write-Host 'Contents:'
    Get-ChildItem -LiteralPath $extractedRoot -Recurse | ForEach-Object {
        Write-Host "  $($_.FullName.Substring($verifyDir.Length + 1))"
    }

    $required = @(
        'tinytown.exe',
        'SDL2.dll',
        'QUICKSTART_TR.txt',
        'QUICKSTART_EN.txt',
        'LICENSE',
        'THIRD-PARTY-NOTICES.md',
        'RUNTIME-REQUIREMENTS.txt'
    )
    foreach ($item in $required) {
        $path = Join-Path $extractedRoot $item
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) {
            throw "Package is missing $item"
        }
        if ((Get-Item -LiteralPath $path).Length -le 0) {
            throw "Package file is empty: $item"
        }
    }
    Write-Host 'all expected files present and non-empty in the archive'

    # The extracted copy must also start, which proves the DLL sits next to the
    # executable in the published layout.
    Push-Location $extractedRoot
    try {
        & '.\tinytown.exe' --help > $null 2>&1
        if ($LASTEXITCODE -ne 0) {
            throw "The extracted executable failed to run --help (exit code $LASTEXITCODE)"
        }
        Write-Host 'extracted executable runs --help successfully'
    } finally {
        Pop-Location
    }
} finally {
    Remove-Item -LiteralPath $stage -Recurse -Force -ErrorAction SilentlyContinue
}
